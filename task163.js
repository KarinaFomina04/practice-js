/* 📌 Задача 163. Для массива целых чисел сначала построй разности соседних значений; затем найди длину минимального отрезка, сортировка которого упорядочит весь массив. Верни объект с подготовленным массивом и ответом; исходный массив не изменяй. Уровень: Middle. */

function prepare(items) {
  return items.slice(1).map((x, i) => x - items[i]);
}

function analyze(a) {
  const sorted = [...a].sort((x, y) => x - y); let left = 0, right = a.length - 1;
  while (left < a.length && a[left] === sorted[left]) left++;
  while (right >= left && a[right] === sorted[right]) right--;
  return right - left + 1;
}

function solve(items) {
  const prepared = prepare(items);
  return { prepared, answer: analyze(prepared) };
}

console.log(JSON.stringify(solve([3, -1, 3, 0, 2]))); // Вывод 1: {"prepared":[-4,4,-3,2],"answer":3}
console.log(JSON.stringify(solve([]))); // Вывод 2: {"prepared":[],"answer":0}
console.log(JSON.stringify(solve([1, 1, 2, 2]))); // Вывод 3: {"prepared":[0,1,0],"answer":2}
