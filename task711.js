/* 📌 Задача 711. Создай замыкание с мемоизацией по содержимому массива; повторный вызов не должен выполнять вычисление, изменение массива должно приводить к новому ключу. Вычисление: составь отчёт о сумме, количестве и среднем, для пустого среднего используй null. Вход содержит конечные целые числа. Уровень: Middle. */

function compute(items) {
  const sum = items.reduce((a, b) => a + b, 0); return {sum, count: items.length, average: items.length ? sum / items.length : null};
}

function createWorker(compute) {
  const cache = new Map(); let calls = 0;
  return items => {
    const key = JSON.stringify(items);
    if (!cache.has(key)) { calls++; cache.set(key, compute(items)); }
    return {value: cache.get(key), calls};
  };
}
const worker = createWorker(compute);
const input = [3, -1, 3, 0];

console.log(JSON.stringify(worker(input))); // Вывод 1: {"value":{"sum":5,"count":4,"average":1.25},"calls":1}
console.log(JSON.stringify(worker([...input]))); // Вывод 2: {"value":{"sum":5,"count":4,"average":1.25},"calls":1}
console.log(JSON.stringify(worker([]))); // Вывод 3: {"value":{"sum":0,"count":0,"average":null},"calls":2}
